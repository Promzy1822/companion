const FE0F = /\uFE0F/g;
const map = [];      // [emoji, iconName]
const imports = new Set(["Sparkles"]);
for (const [names, chars] of GROUPS) {
  const name = names.find(has);
  if (!name) continue;
  imports.add(name);
  for (const ch of Array.from(chars.replace(FE0F, ""))) map.push([ch, name]);
}
if (!has("Sparkles")) { console.error("lucide-react has no Sparkles icon?!"); process.exit(1); }

const importList = Array.from(imports).sort().join(", ");
const entries = map.map(([e, n]) => `  "${e}": ${n},`).join("\n");

